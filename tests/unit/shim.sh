# Makes the mock tests see the head unit's command set (tests/unit/policy.txt).
#
# The scripts under test run in mksh on a PC with GNU tools, so a command the unit
# lacks (printf, head, sed, ...) or an option its toolbox lacks (mv -f, cmp -s)
# would pass here and fail in the car. Source this file (bash) before running them.
# It puts wrappers first on PATH. When the caller is mksh (the code under test),
# a missing command fails as on the unit, and an unsupported toolbox option fails
# too. Both are logged in $GEN5W_UNIT_LOG. Calls from bash or sh test helpers
# go to the PC's tools unchanged.
# tests/unit_commands.py checks the same rules statically.

unit_shim_setup() {
    [ -z "${UNIT_SHIM_OWNED:-}" ] || return 0
    local here dir name kind real allowed letters line
    here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
    dir=$(mktemp -d "${TMPDIR:-/tmp}/gen5w-unit-shim.XXXXXX") || return 1
    mkdir "$dir/bin" || return 1
    : > "$dir/violations"
    UNIT_SHIM_OWNED=$dir
    declare -A opts=() lets=() banned=() toolbox=()
    while read -r name kind; do
        case "$name" in ''|'#'*) continue;; esac
        [ "$kind" = toolbox ] && toolbox[$name]=1
    done < "$here/commands.txt"
    while read -r line; do
        case "$line" in ''|'#'*) continue;; esac
        set -- $line
        case "$1" in
            '!'*) banned[${1#!}]=1; continue;;
        esac
        name=$1; shift
        opts[$name]=; lets[$name]=
        for line in "$@"; do
            case "$line" in +*) lets[$name]=${line#+};; *) opts[$name]="${opts[$name]} $line";; esac
        done
    done < "$here/policy.txt"
    # mksh R43 builtins: the unit never runs a toolbox copy of these from a script.
    for name in cat sleep kill echo test realpath; do unset "toolbox[$name]"; done
    # Interpreters stay static-only: test stubs start with '#!/usr/bin/env python3'
    # and look to these wrappers as if mksh had called them.
    for name in bash dash python3 perl env; do unset "banned[$name]"; done

    for name in "${!banned[@]}" "${!toolbox[@]}"; do
        real=$(command -v "$name" 2>/dev/null)
        case "$real" in /*) ;; *) real=;; esac
        if [ -n "${banned[$name]:-}" ]; then kind=banned; else kind=toolbox; fi
        allowed=${opts[$name]:-}; letters=${lets[$name]:-}
        # The unit has md5 (toolbox); a PC has md5sum with the same output.
        [ "$name" = md5 ] && [ -z "$real" ] && real=$(command -v md5sum)
        if [ "$kind" = toolbox ] && [ -z "$real" ]; then continue; fi
        cat > "$dir/bin/$name" <<EOF
#!/bin/bash
# generated by tests/unit/shim.sh: $name as the head unit has it ($kind)
parent=\$(cat /proc/\$PPID/comm 2>/dev/null)
case "\$parent" in
    mksh*) ;;
    *) [ -n "$real" ] || { echo "$name: not found" >&2; exit 127; }; exec "$real" "\$@";;
esac
violation() { echo "\$1" >> "$dir/violations"; echo "UNIT: \$1" >&2; exit "\$2"; }
if [ $kind = banned ]; then
    violation "$name is not on the head unit: $name \$*" 127
fi
for a in "\$@"; do
    case "\$a" in
        -) break;;
        -*) ;;
        *) break;;
    esac
    ok=no
    for o in $allowed; do [ "\$a" = "\$o" ] && ok=yes; done
    if [ \$ok = no ] && [ -n "$letters" ] && [[ "\$a" =~ ^-[$letters]+\$ ]]; then ok=yes; fi
    [ \$ok = yes ] || violation "the unit's toolbox $name does not take \$a: $name \$*" 1
done
exec "$real" "\$@"
EOF
        chmod 755 "$dir/bin/$name"
    done
    export GEN5W_UNIT_SHIM=$dir GEN5W_UNIT_LOG=$dir/violations PATH="$dir/bin:$PATH"
}

# Prints logged violations; returns 1 if there were any.
unit_shim_report() {
    [ -n "${GEN5W_UNIT_LOG:-}" ] && [ -s "$GEN5W_UNIT_LOG" ] || return 0
    sort -u "$GEN5W_UNIT_LOG" | sed 's/^/FAIL head-unit command: /'
    return 1
}

# Removes the wrappers if this shell made them.
unit_shim_cleanup() {
    [ -n "${UNIT_SHIM_OWNED:-}" ] || return 0
    PATH=${PATH//"$UNIT_SHIM_OWNED/bin:"/}
    hash -r
    rm -rf "$UNIT_SHIM_OWNED"
    UNIT_SHIM_OWNED=
}
